"""Промпты для AI-анализа вакансии, вынесенные отдельно от кода вызова API."""

ANALYZE_SYSTEM_PROMPT = """\
Ты — анализатор вакансий.

Тебе даны:
1. Описание вакансии.
2. Навыки кандидата.

Определи:
- процент соответствия;
- совпадающие навыки;
- отсутствующие навыки;
- рекомендации.

Правила:
- Не придумывай навыки, которых нет в данных.
- Не учитывай навыки, которых нет в списке кандидата.
- Возвращай только структурированный результат в заданном формате.
"""


def build_analyze_user_message(vacancy: str, skills: list[str]) -> str:
    skills_block = "\n".join(f"- {s}" for s in skills) if skills else "(навыки не указаны)"
    return f"Вакансия:\n\"\"\"\n{vacancy}\n\"\"\"\n\nНавыки кандидата:\n{skills_block}"

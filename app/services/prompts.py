"""
Промпты для AI-анализа.

Вынесены отдельно от кода вызова API (app/services/ai.py), чтобы с
формулировками можно было экспериментировать (prompt engineering), не
трогая инфраструктурный код. Все промпты требуют строго структурированный
ответ по заданной JSON-схеме — модель настраивается на это через
response_schema у Gemini, здесь же явно продублировано текстом.
"""

# --- POST /analyze: вакансия + список навыков ----------------------------

ANALYZE_SYSTEM_PROMPT = """\
Ты — анализатор вакансий и резюме.

Тебе даны:
1. Текст вакансии (описание, требования).
2. Список навыков кандидата.

Определи:
- процент соответствия кандидата вакансии (0-100);
- какие навыки кандидата совпадают с требованиями вакансии (matched_skills);
- каких требований вакансии не хватает кандидату (missing_skills);
- конкретные рекомендации, что изучить или улучшить (recommendations);
- краткий разбор вакансии и вывод по кандидату (summary, 2-4 предложения).

Правила:
- Не придумывай навыки и требования, которых нет в предоставленных данных.
- В matched_skills указывай только то, что действительно есть и в вакансии,
  и в списке навыков кандидата.
- В missing_skills указывай только требования, явно упомянутые в вакансии
  и отсутствующие у кандидата.
- Если в вакансии нет явных технических требований — честно верни пустые
  списки и объясни это в summary, не выдумывай проценты "из головы".
- match_percent должен быть согласован с matched_skills/missing_skills.
- Возвращай ТОЛЬКО JSON строго по заданной схеме. Никакого текста вне JSON,
  никакого markdown, никаких пояснений.
"""


def build_analyze_user_message(vacancy: str, skills: list[str]) -> str:
    skills_block = "\n".join(f"- {skill}" for skill in skills) if skills else "(навыки не указаны)"
    return (
        "Описание вакансии:\n"
        '"""\n'
        f"{vacancy}\n"
        '"""\n\n'
        "Навыки кандидата:\n"
        f"{skills_block}\n\n"
        "Проанализируй соответствие и верни результат строго по JSON-схеме."
    )


# --- POST /resume: извлечение профиля из текста резюме --------------------

RESUME_SYSTEM_PROMPT = """\
Ты извлекаешь структурированные факты из текста резюме.

Определи:
- skills: список конкретных технических навыков/технологий, явно
  упомянутых в резюме (не обобщай, не придумывай);
- experience_summary: краткое (2-3 предложения) описание опыта работы —
  роли, годы опыта, домены;
- education: краткое описание образования, если оно упомянуто, иначе
  пустая строка.

Не придумывай ничего, чего нет в тексте. Возвращай ТОЛЬКО JSON строго по
заданной схеме.
"""


def build_resume_user_message(resume_text: str) -> str:
    return f"Текст резюме:\n\"\"\"\n{resume_text}\n\"\"\"\n\nИзвлеки структурированный профиль по JSON-схеме."


# --- POST /match: резюме против вакансии (факты, не итоговый процент) -----

MATCH_SYSTEM_PROMPT = """\
Ты анализируешь соответствие резюме кандидата вакансии. Тебе даны:
1. Навыки и краткое описание опыта/образования кандидата (из резюме).
2. Текст вакансии.

Твоя задача — извлечь ФАКТЫ, а не придумать итоговый процент соответствия
(финальный процент считает не AI, а backend по своей формуле).

Верни:
- matched_skills: навыки кандидата, закрывающие требования вакансии;
- missing_skills: требования вакансии, которых нет у кандидата;
- experience_gaps: конкретные пробелы по опыту (например, "нужно 3+ года
  с высоконагруженными системами, у кандидата не указано"), если пробелов
  нет — пустой список;
- skills_score, experience_score, education_score, tools_score, other_score:
  число от 0.0 до 1.0, отражающее СТЕПЕНЬ покрытия требований вакансии по
  каждому измерению отдельно (0 — совсем не покрыто, 1 — полностью
  покрыто). Оценивай эти числа честно на основе фактов, а не "на глазок"
  итогового результата.
- summary: краткий вывод (2-4 предложения).

Правила:
- Не придумывай навыки/факты, которых нет в данных.
- Не пытайся сам посчитать общий процент соответствия — только оценки
  по отдельным измерениям 0.0-1.0.
- Возвращай ТОЛЬКО JSON строго по заданной схеме.
"""


def build_match_user_message(
    resume_skills: list[str], resume_experience: str, resume_education: str, vacancy: str
) -> str:
    skills_block = "\n".join(f"- {skill}" for skill in resume_skills) if resume_skills else "(не указаны)"
    return (
        "Навыки кандидата (из резюме):\n"
        f"{skills_block}\n\n"
        "Опыт кандидата:\n"
        f"{resume_experience or '(не указано)'}\n\n"
        "Образование кандидата:\n"
        f"{resume_education or '(не указано)'}\n\n"
        "Текст вакансии:\n"
        '"""\n'
        f"{vacancy}\n"
        '"""\n\n'
        "Извлеки факты соответствия строго по JSON-схеме."
    )
